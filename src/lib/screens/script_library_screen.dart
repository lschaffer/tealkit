  Future<void> _openSshConnectionDialog() async {
    final ds = DataSourcesSettingsService.instance;
    if (!ds.isLoaded) await ds.load();
    if (!mounted) return;

    // Pre-fill with per-script override, or fall back to global settings
    final initHost = _sshHost.isNotEmpty ? _sshHost : ds.sshHost;
    final initPort = _sshHost.isNotEmpty ? _sshPort : ds.sshPort;
    final initUser = _sshUsername.isNotEmpty ? _sshUsername : ds.sshUsername;
    final initPass = _sshPassword.isNotEmpty ? _sshPassword : ds.sshPassword;

    final result = await showDialog<Map<String, dynamic>>(
      context: context,
      builder: (_) => _SshConnectionDialog(host: initHost, port: initPort, username: initUser, password: initPass),
    );

    if (result != null && mounted) {
      setState(() {
        _sshHost = result['host'] as String? ?? '';
        _sshPort = result['port'] as int? ?? 22;
        _sshUsername = result['username'] as String? ?? '';
        _sshPassword = result['password'] as String? ?? '';
      });
    }
  }
}

