class _ScriptEditorDialog extends ConsumerStatefulWidget {
  const _ScriptEditorDialog({this.existing, this.onInsertScriptPrompt});

  final ShellScript? existing;
  final void Function(String scriptName)? onInsertScriptPrompt;

  static Future<bool?> show(
    BuildContext context, {
    required WidgetRef ref,
    ShellScript? existing,
    void Function(String scriptName)? onInsertScriptPrompt,
  }) {
    return showDialog<bool>(
      context: context,
      barrierDismissible: false,
      builder: (_) => _ScriptEditorDialog(existing: existing, onInsertScriptPrompt: onInsertScriptPrompt),
    );
  }

  @override
  ConsumerState<_ScriptEditorDialog> createState() => _ScriptEditorDialogState();
}

class _ScriptEditorDialogState extends ConsumerState<_ScriptEditorDialog> {
  static const String _defaultGenerationSystemPrompt =
      'You are an expert Linux shell scripting assistant. '
      'Generate clean, production-quality bash/sh scripts with correct syntax. '
      'Validate the script mentally before output. '
      'Output only the script code, no preamble or explanation.';

  late final TextEditingController _nameCtrl;
  late final TextEditingController _descCtrl;
  late final TextEditingController _contentCtrl;
  late final TextEditingController _generatePromptCtrl;
  late final TextEditingController _systemPromptCtrl;

  bool _saving = false;
  bool _generating = false;
  bool _testing = false;
  bool _includeComments = true;
  // 'llm1' = global LLM 1, 'llm2' = global LLM 2
  String _codeLlmChoice = 'llm1';

  String _sshHost = '';
  int _sshPort = 22;
  String _sshUsername = '';
  String _sshPassword = '';
  int _timeoutSeconds = 120;
  bool _runLocally = false;
  late TextEditingController _timeoutCtrl;

  bool get _hasLocalSshConfig => _sshHost.isNotEmpty && _sshUsername.isNotEmpty;
  bool get _hasSshForTest => _hasLocalSshConfig || DataSourcesSettingsService.instance.isSshConfigured;
  bool get _canUseLocalShellMode => (Platform.isLinux || Platform.isMacOS) && !(ref.read(serverModeProvider).value?.isRemote ?? false);
  bool get _canTestRun => _runLocally ? (Platform.isLinux || Platform.isMacOS) : _hasSshForTest;

  Widget _buildCommentsToggle(ThemeData theme) {
    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        Text(L.of(context).withCommentsLabel, style: theme.textTheme.bodySmall?.copyWith(color: theme.colorScheme.onSurfaceVariant)),
        Switch(
          value: _includeComments,
          onChanged: (value) => setState(() => _includeComments = value),
          materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
        ),
      ],
    );
  }

  @override
  void initState() {
    super.initState();
    final s = widget.existing;
    _nameCtrl = TextEditingController(text: s?.name ?? '');
    _descCtrl = TextEditingController(text: s?.description ?? '');
    _contentCtrl = TextEditingController(text: s?.content ?? '');
    _generatePromptCtrl = TextEditingController(text: s?.generationPrompt ?? '');
    _systemPromptCtrl = TextEditingController(text: s?.generationSystemPrompt ?? _defaultGenerationSystemPrompt);
    _sshHost = s?.sshHost ?? '';
    _sshPort = s?.sshPort ?? 22;
    _sshUsername = s?.sshUsername ?? '';
    _sshPassword = s?.sshPassword ?? '';
    _timeoutSeconds = s?.timeoutSeconds ?? 120;
    _runLocally = (s?.runLocally ?? false) && _canUseLocalShellMode;
    _timeoutCtrl = TextEditingController(text: _timeoutSeconds.toString());
  }

  @override
  void dispose() {
    _nameCtrl.dispose();
    _descCtrl.dispose();
    _contentCtrl.dispose();
    _generatePromptCtrl.dispose();
    _systemPromptCtrl.dispose();
    _timeoutCtrl.dispose();
    super.dispose();
  }

  Future<void> _save() async {
    final name = _nameCtrl.text.trim();
    if (name.isEmpty) {
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text(L.of(context).scriptNameRequiredMsg), backgroundColor: Colors.orange));
      return;
    }
    setState(() => _saving = true);
    try {
      final svc = ScriptLibraryService.instance;
      final genPrompt = _generatePromptCtrl.text.trim();
      final client = (ref.read(serverModeProvider).value?.isRemote ?? false)
          ? ref.read(serverApiClientProvider)
          : null;
      if (widget.existing != null) {
        final updated = widget.existing!.copyWith(
          name: name,
          description: _descCtrl.text.trim(),
          content: _contentCtrl.text,
          generationSystemPrompt: _systemPromptCtrl.text.trim(),
          generationPrompt: genPrompt.isNotEmpty ? genPrompt : null,
          sshHost: _sshHost,
          sshPort: _sshPort,
          sshUsername: _sshUsername,
          sshPassword: _sshPassword,
          timeoutSeconds: _timeoutSeconds,
          runLocally: _runLocally,
        );
        await svc.updateScript(updated, client);
      } else {
        await svc.addScript(
          name: name,
          description: _descCtrl.text.trim(),
          content: _contentCtrl.text,
          generationSystemPrompt: _systemPromptCtrl.text.trim(),
          generationPrompt: genPrompt,
          sshHost: _sshHost,
          sshPort: _sshPort,
          sshUsername: _sshUsername,
          sshPassword: _sshPassword,
          timeoutSeconds: _timeoutSeconds,
          runLocally: _runLocally,
          client: client,
        );
      }
      if (mounted) Navigator.of(context).pop(true);
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(SnackBar(content: Text(L.of(context).scriptSaveFailed(e.toString())), backgroundColor: AppTheme.error));
      }
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  Future<void> _generateScript() async {
    final prompt = _generatePromptCtrl.text.trim();
    if (prompt.isEmpty) {
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text(L.of(context).describeForGeneration), backgroundColor: Colors.orange));
      return;
    }

    final llmSettings = ref.read(llmSettingsProvider);
    LLMService? effectiveLlm;

    if (_codeLlmChoice == 'llm2' && llmSettings.isConfigured2) {
      // Use LLM 2 (coding)
      final llm2 = LLMService();
      await TaskRunnerService.configureLlmFromParams(
        llmService: llm2,
        providerKey: llmSettings.provider2.configKey,
        model: llmSettings.model2,
        apiKey: llmSettings.apiKey2,
        baseUrl: llmSettings.baseUrl2,
      );
      if (llm2.isConfigured) effectiveLlm = llm2;
    }

    // Fallback: LLM 1 → LLM 2
    if (effectiveLlm == null) {
      if (llmSettings.isConfigured) {
        final fallback = LLMService();
        await fallback.loadSavedProviderAndModel();
        if (fallback.isConfigured) effectiveLlm = fallback;
      } else if (llmSettings.isConfigured2) {
        final llm2 = LLMService();
        await TaskRunnerService.configureLlmFromParams(
          llmService: llm2,
          providerKey: llmSettings.provider2.configKey,
          model: llmSettings.model2,
          apiKey: llmSettings.apiKey2,
          baseUrl: llmSettings.baseUrl2,
        );
        if (llm2.isConfigured) effectiveLlm = llm2;
      }
    }

    if (effectiveLlm == null) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(L.of(context).noLlmForScript), backgroundColor: Colors.orange));
      return;
    }

    setState(() => _generating = true);
    try {
      final rules = <String>[
        'Output ONLY the bash script, starting with #!/bin/bash',
        if (_includeComments) 'Add brief inline comments for each major step',
        if (!_includeComments) 'Do NOT include comments in the script',
        'Handle errors with set -e and appropriate error messages',
        'Do NOT include any explanation outside the script itself',
        'Do NOT wrap the output in markdown code fences',
      ];

      final metaPrompt =
          '''Generate a Linux/Unix bash shell script that does the following:

$prompt

Rules:
- ${rules.join('\n- ')}''';

      final baseSystemPrompt = _systemPromptCtrl.text.trim().isNotEmpty ? _systemPromptCtrl.text.trim() : _defaultGenerationSystemPrompt;
      final systemPrompt = StringBuffer(baseSystemPrompt);
      if (!_includeComments) {
        systemPrompt.write(' Do not include comments.');
      }

      final response = await effectiveLlm.generateChatCompletion(
        messages: [
          ChatMessage(id: const Uuid().v4(), role: ChatRole.system, content: systemPrompt.toString(), timestamp: DateTime.now()),
          ChatMessage(id: const Uuid().v4(), role: ChatRole.user, content: metaPrompt, timestamp: DateTime.now()),
        ],
        maxTokens: 1024,
      );

      var script = response.content.trim();

      // Strip markdown code fences if model added them anyway.
      if (script.startsWith('```')) {
        final lines = script.split('\n');
        script = lines.skip(1).where((l) => !l.startsWith('```')).join('\n').trim();
      }

      if (mounted) {
        setState(() => _contentCtrl.text = script);

        // Auto-fill name if empty.
        if (_nameCtrl.text.isEmpty) {
          final firstLine = prompt.split('\n').first;
          final name = firstLine.length > 40 ? '${firstLine.substring(0, 37)}...' : firstLine;
          _nameCtrl.text = name;
          _descCtrl.text = prompt.length > 120 ? '${prompt.substring(0, 117)}...' : prompt;
        }
      }
    } catch (e) {
      log.error('[ScriptLibrary] LLM generation failed: $e');
      if (mounted) {
        ScaffoldMessenger.of(
          context,
        ).showSnackBar(SnackBar(content: Text(L.of(context).scriptGenerationFailed(e.toString())), backgroundColor: AppTheme.error));
      }
    } finally {
      if (mounted) setState(() => _generating = false);
    }
  }

  Future<void> _testRun() async {
    final scriptName = _nameCtrl.text.trim();
    final content = _contentCtrl.text.trim();
    if (content.isEmpty) {
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(const SnackBar(content: Text('No script content to test.'), backgroundColor: Colors.orange));
      return;
    }

    if (!_runLocally && !_hasSshForTest) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('SSH not configured. Tap the Server button to set connection details.'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }

    final argsCtrl = TextEditingController();
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text('Test Run${scriptName.isNotEmpty ? ': $scriptName' : ''}'),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Parameters (optional args passed to the script):',
              style: Theme.of(ctx).textTheme.bodySmall?.copyWith(color: Theme.of(ctx).colorScheme.onSurfaceVariant),
            ),
            const SizedBox(height: 8),
            TextField(
              controller: argsCtrl,
              decoration: const InputDecoration(hintText: 'e.g. /var/log --verbose', border: OutlineInputBorder()),
              autofocus: true,
            ),
          ],
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(ctx, false), child: const Text('Cancel')),
          FilledButton.icon(
            onPressed: () => Navigator.pop(ctx, true),
            icon: const Icon(Icons.play_arrow, size: 18),
            label: const Text('Run'),
            style: FilledButton.styleFrom(backgroundColor: AppTheme.primaryBlue),
          ),
        ],
      ),
    );
    final args = argsCtrl.text.trim();
    // Defer disposal so the dialog's pop animation can finish before the
    // controller is torn down. Disposing immediately causes the TextField's
    // cursor AnimatedWidget to call addListener on an already-disposed
    // ChangeNotifier while the route is still fading out.
    Future<void>.delayed(const Duration(milliseconds: 500), argsCtrl.dispose);
    if (confirmed != true || !mounted) return;

    setState(() => _testing = true);
    Map<String, dynamic> result;
    try {
      result = await SshMcpServer.runContentForTest(
        content,
        args: args,
        runLocally: _runLocally,
        sshHost: _sshHost,
        sshPort: _sshPort,
        sshUsername: _sshUsername,
        sshPassword: _sshPassword,
      );
    } catch (e) {
      result = {'error': e.toString()};
    } finally {
      if (mounted) setState(() => _testing = false);
    }

    if (!mounted) return;

    final isError = result.containsKey('error');
    final stdout = result['stdout'] as String? ?? '';
    final stderr = result['stderr'] as String? ?? '';
    final exitCode = result['exitCode'] as int?;
    final error = result['error'] as String?;

    await showDialog<void>(
      context: context,
      builder: (ctx) {
        final screenSize = MediaQuery.of(ctx).size;
        final isMobile = screenSize.width < 600;
        return Dialog(
          insetPadding: isMobile ? EdgeInsets.zero : const EdgeInsets.symmetric(horizontal: 24, vertical: 32),
          clipBehavior: Clip.antiAlias,
          shape: isMobile ? const RoundedRectangleBorder() : null,
          child: SizedBox(
            width: isMobile ? screenSize.width : 680,
            height: isMobile ? screenSize.height : null,
            child: SafeArea(
              child: Column(
                children: [
                  Padding(
                    padding: const EdgeInsets.fromLTRB(20, 16, 8, 0),
                    child: Row(
                      children: [
                        Icon(
                          isError ? Icons.error_outline : (exitCode == 0 ? Icons.check_circle_outline : Icons.warning_amber_outlined),
                          color: isError || (exitCode != null && exitCode != 0) ? AppTheme.error : Colors.green,
                        ),
                        const SizedBox(width: 12),
                        Expanded(
                          child: Text(
                            isError ? 'Test Run Failed' : 'Test Output (exit code: $exitCode)',
                            style: Theme.of(ctx).textTheme.titleMedium?.copyWith(fontWeight: FontWeight.w700),
                          ),
                        ),
                        IconButton(icon: const Icon(Icons.close), onPressed: () => Navigator.of(ctx).pop()),
                      ],
                    ),
                  ),
                  const Divider(height: 1),
                  Flexible(
                    child: SingleChildScrollView(
                      padding: const EdgeInsets.all(16),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          if (isError) ...[
                            Text(
                              'Error:',
                              style: TextStyle(color: AppTheme.error, fontWeight: FontWeight.bold),
                            ),
                            const SizedBox(height: 4),
                            _OutputBox(text: error ?? ''),
                          ] else ...[
                            if (stdout.isNotEmpty) ...[
                              const Text('stdout:', style: TextStyle(fontWeight: FontWeight.bold)),
                              const SizedBox(height: 4),
                              _OutputBox(text: stdout),
                              if (stderr.isNotEmpty) const SizedBox(height: 12),
                            ],
                            if (stderr.isNotEmpty) ...[
                              Text(
                                'stderr:',
                                style: TextStyle(color: AppTheme.error, fontWeight: FontWeight.bold),
                              ),
                              const SizedBox(height: 4),
                              _OutputBox(text: stderr),
                            ],
                            if (stdout.isEmpty && stderr.isEmpty) const Text('(no output)', style: TextStyle(color: Colors.grey)),
                          ],
                        ],
                      ),
                    ),
                  ),
                  const Divider(height: 1),
                  Padding(
                    padding: const EdgeInsets.all(12),
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.end,
                      children: [FilledButton(onPressed: () => Navigator.of(ctx).pop(), child: const Text('Close'))],
                    ),
                  ),
                ],
              ),
            ),
          ),
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isNew = widget.existing == null;
    final screenSize = MediaQuery.of(context).size;
    final isMobile = screenSize.width < 600;
