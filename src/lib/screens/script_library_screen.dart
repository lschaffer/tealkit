/// Full-screen view for managing the global shell script library.
///
/// Scripts can be created, edited, deleted, and generated by the LLM.
/// Each script is persisted via [ScriptLibraryService].
class ScriptLibraryScreen extends ConsumerStatefulWidget {
  const ScriptLibraryScreen({super.key, this.onInsertScriptPrompt});

  final void Function(String scriptName)? onInsertScriptPrompt;

  /// Push the screen and return [true] if any changes were made.
  static Future<bool?> show(BuildContext context, {void Function(String scriptName)? onInsertScriptPrompt}) {
    return Navigator.of(context).push<bool>(
      MaterialPageRoute(fullscreenDialog: true, builder: (_) => ScriptLibraryScreen(onInsertScriptPrompt: onInsertScriptPrompt)),
    );
  }

  @override
  ConsumerState<ScriptLibraryScreen> createState() => _ScriptLibraryScreenState();
}

class _ScriptLibraryScreenState extends ConsumerState<ScriptLibraryScreen> {
  bool _loading = true;
  List<ShellScript> _scripts = [];
  bool _changed = false;

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    final client = (ref.read(serverModeProvider).value?.isRemote ?? false)
        ? ref.read(serverApiClientProvider)
        : null;
    await ScriptLibraryService.instance.load(client);
    if (!mounted) return;
    setState(() {
      _scripts = List.from(ScriptLibraryService.instance.scripts);
      _loading = false;
    });
  }

  void _refresh() {
    setState(() {
      _scripts = List.from(ScriptLibraryService.instance.scripts);
      _changed = true;
    });
  }

  Future<void> _loadSamples() async {
    final svc = ScriptLibraryService.instance;
    final samples = [
      (
        name: 'Disk Usage',
        description: 'Shows disk usage for all mounted filesystems (df -h) sorted by use%.',
        content:
            '#!/bin/bash\n'
            '# Disk usage — all mounted filesystems sorted by use%\n'
            'df -h --output=source,size,used,avail,pcent,target 2>/dev/null | '
            '(read header; echo "\$header"; sort -rk5 -t\' \') || df -h\n',
      ),
      (
        name: 'Biggest Files in /usr/lib',
        description: 'Lists the 20 largest files under /usr/lib, sorted by size descending.',
        content:
            '#!/bin/bash\n'
            '# 20 biggest files in /usr/lib\n'
            'find /usr/lib -maxdepth 5 -type f -printf "%s\\t%p\\n" 2>/dev/null | '
            'sort -rn | head -20 | '
            'awk \'{printf "%-10s %s\\n", (\$1>1073741824 ? sprintf("%.1fG",\$1/1073741824) : \$1>1048576 ? sprintf("%.1fM",\$1/1048576) : sprintf("%.0fK",\$1/1024)), \$2}\'\n',
      ),
      (
        name: 'Top 10 Processes',
        description: 'Shows the 10 processes consuming the most CPU, with user, PID, CPU%, MEM% and command.',
        content:
            '#!/bin/bash\n'
            '# Top 10 processes by CPU usage\n'
            'ps aux --sort=-%cpu 2>/dev/null | head -11 || ps aux | head -11\n',
      ),
    ];

    final existingNames = _scripts.map((s) => s.name).toSet();
    int added = 0;
    final client = (ref.read(serverModeProvider).value?.isRemote ?? false)
        ? ref.read(serverApiClientProvider)
        : null;
    for (final s in samples) {
      if (existingNames.contains(s.name)) continue;
      await svc.addScript(name: s.name, description: s.description, content: s.content, client: client);
      added++;
    }
    _refresh();
    if (mounted) {
      final msg = added == 0 ? 'All sample scripts already exist.' : '$added sample script${added == 1 ? '' : 's'} added.';
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(msg), behavior: SnackBarBehavior.floating));
    }
  }

  Future<void> _openEditor({ShellScript? existing}) async {
    final result = await _ScriptEditorDialog.show(context, ref: ref, existing: existing, onInsertScriptPrompt: widget.onInsertScriptPrompt);
    if (result == true) _refresh();
  }

  Future<void> _deleteScript(ShellScript script) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(L.of(context).deleteScriptTitle),
        content: Text(L.of(context).deleteScriptConfirm(script.name)),
        actions: [
          TextButton(onPressed: () => Navigator.pop(ctx, false), child: Text(L.of(context).cancel)),
          TextButton(
            onPressed: () => Navigator.pop(ctx, true),
            child: Text(L.of(context).delete, style: TextStyle(color: AppTheme.error)),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    final client = (ref.read(serverModeProvider).value?.isRemote ?? false)
        ? ref.read(serverApiClientProvider)
        : null;
    await ScriptLibraryService.instance.deleteScript(script.id, client);
    _refresh();
    if (mounted) {
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text(L.of(context).scriptDeletedMsg(script.name)), behavior: SnackBarBehavior.floating));
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Scaffold(
      appBar: AppBar(
        title: Text(L.of(context).shellScriptLibraryTitle),
        leading: IconButton(icon: const Icon(Icons.close), onPressed: () => Navigator.of(context).pop(_changed)),
        actions: [
          IconButton(icon: const Icon(Icons.science_outlined), tooltip: 'Load sample scripts', onPressed: _loadSamples),
          IconButton(icon: const Icon(Icons.add), tooltip: L.of(context).newScriptTooltip, onPressed: () => _openEditor()),
        ],
      ),
      body: _loading
          ? const Center(child: CircularProgressIndicator())
          : _scripts.isEmpty
          ? Center(
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Icon(Icons.terminal, size: 64, color: Colors.grey[400]),
                  const SizedBox(height: 16),
                  Text(L.of(context).noScriptsYet, style: theme.textTheme.titleMedium?.copyWith(color: Colors.grey[500])),
                  const SizedBox(height: 8),
                  Text(L.of(context).createFirstScriptHint, style: theme.textTheme.bodySmall?.copyWith(color: Colors.grey[400])),
                  const SizedBox(height: 24),
                  FilledButton.icon(
                    onPressed: () => _openEditor(),
                    icon: const Icon(Icons.add),
                    label: Text(L.of(context).createScriptButton),
                  ),
                  const SizedBox(height: 12),
                  OutlinedButton.icon(
                    onPressed: _loadSamples,
                    icon: const Icon(Icons.science_outlined, size: 18),
                    label: const Text('Load sample scripts'),
                  ),
                ],
              ),
            )
          : ListView.separated(
              padding: const EdgeInsets.symmetric(vertical: 8),
              itemCount: _scripts.length,
              separatorBuilder: (context, idx) => const Divider(height: 1, indent: 72),
              itemBuilder: (ctx, i) {
                final s = _scripts[i];
                return ListTile(
                  leading: CircleAvatar(
                    backgroundColor: AppTheme.primaryBlue.withValues(alpha: 0.12),
                    child: const Icon(Icons.terminal, color: AppTheme.primaryBlue, size: 20),
                  ),
                  title: Text(s.name, style: const TextStyle(fontWeight: FontWeight.w600)),
                  subtitle: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      if (s.description.isNotEmpty)
                        Text(s.description, maxLines: 1, overflow: TextOverflow.ellipsis)
                      else
                        Text('${'\n'.allMatches(s.content).length + 1} lines', style: TextStyle(color: Colors.grey[500], fontSize: 12)),
                      const SizedBox(height: 2),
                      Text(
                        'Mode: ${s.runLocally ? 'Local' : 'SSH'}',
                        style: TextStyle(
                          color: s.runLocally ? AppTheme.success : Colors.grey[500],
                          fontSize: 11,
                          fontWeight: FontWeight.w600,
                        ),
                      ),
                    ],
                  ),
                  trailing: Row(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      IconButton(
                        icon: const Icon(Icons.edit_outlined),
                        tooltip: L.of(context).editScriptTooltip,
                        onPressed: () => _openEditor(existing: s),
                      ),
                      IconButton(
                        icon: Icon(Icons.delete_outline, color: AppTheme.error),
                        tooltip: L.of(context).deleteScriptTooltip,
                        onPressed: () => _deleteScript(s),
                      ),
                    ],
                  ),
                  onTap: () => _openEditor(existing: s),
                );
              },
            ),
    );
  }
}

